const outputRoot = "crates/harn-stdlib/src/stdlib/cli/localization";
const marker = "/** Generated by scripts/generate_cli_localization.mjs. Do not edit. */\n";
const assert = (condition, message) => { if (!condition) throw new Error(message); };
assert(registry.schema_version === 1 && Object.keys(registry.messages).length > 0, "missing script message registry");
assert(/^HARN_[A-Z_]+$/.test(registry.locale_env), "invalid normalized-locale input contract");
const environmentNames = fs.readFileSync(path.join(root, "crates/harn-vm/src/environment_registry_names.txt"), "utf8").split(/\r?\n/);
assert(environmentNames.includes(registry.locale_env), "normalized locale port is absent from the owning environment registry");

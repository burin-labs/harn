const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "harn-cli-localization-"));
try {
  for (const [relative, contents] of outputs) {
    const target = path.join(temporary, relative);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, contents);
  }
  run(["fmt", temporary, "--json"]);
  const mismatches = [];
  const projectionRoot = path.join(root, outputRoot);
  assert(fs.realpathSync(path.dirname(projectionRoot)) === path.dirname(projectionRoot), "CLI localization output parent must not traverse symlinks");
  if (fs.existsSync(projectionRoot)) {
    assert(fs.realpathSync(projectionRoot) === projectionRoot, "CLI localization output root must not traverse symlinks");
    const directories = [projectionRoot];
    for (const directory of directories) {
      for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        assert(!entry.isSymbolicLink(), "CLI localization output must not contain symlinks");
        if (entry.isDirectory()) {
          directories.push(path.join(directory, entry.name));
          continue;
        }
        if (!entry.isFile()) continue;
        const relative = path.relative(root, path.join(directory, entry.name)).split(path.sep).join("/");
        if (!outputs.has(relative)) {
          if (check) {
            mismatches.push(relative);
            continue;
          }
          assert(previousModules.has(relative), `unregistered CLI localization output: ${relative}`);
          const target = path.join(root, relative);
          assert(fs.realpathSync(target).startsWith(projectionRoot + path.sep), "CLI localization projection escaped its output root");
          assert(/^\/\*\*\s*\*?\s*Generated by scripts\/generate_cli_localization\.mjs\./.test(fs.readFileSync(target, "utf8")), "previous CLI localization projection has unknown contents");
          fs.rmSync(target);
        }
      }
    }
  }
  for (const relative of outputs.keys()) {
    const formatted = fs.readFileSync(path.join(temporary, relative), "utf8");
    const target = path.join(root, relative);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== formatted) mismatches.push(relative);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, formatted);
    }
  }
  assert(mismatches.length === 0, `stale CLI localization projections (${mismatches.length}):\n${mismatches.join("\n")}`);
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}

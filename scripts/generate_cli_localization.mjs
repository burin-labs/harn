// This is build-time projection, never a runtime formatter. Every numbered slot
// becomes one direct list access in generated Harn source; raw values are not
// parsed, replaced, or used as templates.
function expression(template, arity) {
  assert(typeof template === "string" && template.trim(), "missing script translation");
  const pieces = [];
  const slots = [];
  const tokens = /\{\{|\}\}|\{(\d+)\}/g;
  let cursor = 0;
  let literal = "";
  const flush = () => { if (literal) { pieces.push(JSON.stringify(literal)); literal = ""; } };
  for (const match of template.matchAll(tokens)) {
    const text = template.slice(cursor, match.index);
    assert(!/[{}]/.test(text), `unregistered template syntax: ${template}`);
    literal += text;
    if (match[0] === "{{") literal += "{";
    else if (match[0] === "}}") literal += "}";
    else {
      flush();
      const slot = Number(match[1]);
      assert(slot < arity, `out-of-range slot: ${template}`);
      slots.push(slot);
      // Arity excludes missing values; indexing remains nullable to the checker.
      pieces.push(`(values[${slot}] ?? "")`);
    }
    cursor = match.index + match[0].length;
  }
  const tail = template.slice(cursor);
  assert(!/[{}]/.test(tail), `unregistered template syntax: ${template}`);
  literal += tail;
  flush();
  assert(JSON.stringify(slots.sort((a, b) => a - b)) === JSON.stringify(Array.from({ length: arity }, (_, i) => i)), `changed argument slots: ${template}`);
  return pieces.length ? pieces.join(" + ") : '""';
}

function run(arguments_) {
  const result = spawnSync(binary, arguments_, { cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  assert(result.status === 0, `${binary} ${arguments_.join(" ")} failed: ${result.stderr || result.error || result.stdout}`);
  return result.stdout;
}

assert(expression("literal {{0}} %@ {0}", 1) === '"literal {0} %@ " + (values[0] ?? "")', "literal template control failed");
for (const [template, arity] of [["missing {0}", 2], ["duplicate {0} {0}", 1], ["unknown {1}", 1], ["implicit {}", 1]]) {
  let rejected = false;
  try { expression(template, arity); } catch { rejected = true; }
  assert(rejected, `invalid slot contract accepted: ${template}`);
}

function* nodes(value) {
  if (Array.isArray(value)) { for (const item of value) yield* nodes(item); }
  else if (value && typeof value === "object") {
    if (value.kind) yield value;
    for (const item of Object.values(value)) yield* nodes(item);
  }
}

const outputs = new Map();
outputs.set(`${outputRoot}.harn`, `/**\n * Generated by scripts/generate_cli_localization.mjs. Do not edit.\n * Read the normalized locale selected by the CLI host.\n * @effects: [env.read]\n * @errors: []\n */\npub fn cli_locale(env: HarnessEnv) -> string {\n  return env.get_or(${JSON.stringify(registry.locale_env)}, "en")\n}\n`);
let expectedCalls = 0;
let measuredCalls = 0;
const referenced = new Set();
for (const [relative, surface] of Object.entries(registry.sources)) {
  assert(relative.startsWith("crates/harn-stdlib/src/stdlib/cli/") && relative.endsWith(".harn") && !relative.includes(".."), `invalid script path: ${relative}`);
  const namespace = relative.slice("crates/harn-stdlib/src/stdlib/cli/".length, -5);
  const keys = Object.keys(surface.calls).sort();
  assert(keys.length > 0, `empty localized surface: ${relative}`);
  const entry = [];
  for (let start = 0; start < keys.length; start += 5) {
    const part = Math.floor(start / 5);
    const selected = keys.slice(start, start + 5);
    const names = selected.map((_, index) => `message_${start + index}`);
    entry.push(`import { ${names.join(", ")} } from "std/cli/localization/${namespace}/part_${part}"`);
    const lines = [];
    for (const [index, key] of selected.entries()) {
      const arity = registry.messages[key];
      assert(Number.isInteger(arity) && arity >= 0 && arity <= 100, `invalid argument contract: ${key}`);
      assert(Number.isInteger(surface.calls[key]) && surface.calls[key] > 0, `invalid call count: ${key}`);
      referenced.add(key);
      lines.push("", "/**", ...(index === 0 ? [" * Generated by scripts/generate_cli_localization.mjs. Do not edit."] : []), " * Render one registered CLI message from literal argument values.", " * @effects: []", ' * @errors: ["CLI localization argument count does not match its registered template"]', " */", `pub fn ${names[index]}(locale: string, values: list<string>) -> string {`, `  if len(values) != ${arity} {`, '    throw "CLI localization argument count does not match its registered template"', "  }");
      for (const locale of locales.filter((locale) => locale !== "en")) {
        lines.push(`  if locale == ${JSON.stringify(locale)} {`, `    return ${expression(catalogs[locale][key], arity)}`, "  }");
      }
      lines.push(`  return ${expression(catalogs.en[key], arity)}`, "}");
    }
    outputs.set(`${outputRoot}/${namespace}/part_${part}.harn`, `${lines.join("\n")}\n`);
  }
  entry.push("", "/**", " * Select a registered CLI template without interpreting argument text.", " * @effects: []", ' * @errors: ["Unregistered CLI localization message", "CLI localization argument count does not match its registered template"]', " */", "pub fn cli_message(locale: string, source: string, values: list<string>) -> string {");
  for (const [index, key] of keys.entries()) entry.push(`  if source == ${JSON.stringify(key)} {`, `    return message_${index}(locale, values)`, "  }");
  entry.push('  throw "Unregistered CLI localization message"', "}");
  outputs.set(`${outputRoot}/${namespace}.harn`, marker + entry.join("\n") + "\n");
  expectedCalls += Object.values(surface.calls).reduce((sum, count) => sum + count, 0);
  if (check) {
    const parsed = JSON.parse(run(["parse", path.join(root, relative), "--json"]));
    assert(parsed.ok && parsed.schemaVersion === 1 && parsed.data?.kind === "Program", `unmeasured script: ${relative}`);
    assert(parsed.data.body.some((node) => node.kind === "SelectiveImport" && node.fields.path === `std/cli/localization/${namespace}` && node.fields.names.includes("cli_message")), `missing owning localization import: ${relative}`);
    const counts = {};
    for (const node of nodes(parsed.data)) {
      if (node.kind !== "FunctionCall" || node.fields.name !== "cli_message") continue;
      const arguments_ = node.fields.args;
      assert(arguments_.length === 3 && arguments_[0].kind === "Identifier" && arguments_[0].fields === "__cli_locale" && arguments_[1].kind === "StringLiteral" && arguments_[2].kind === "ListLiteral" && Array.isArray(arguments_[2].fields), `invalid explicit localization call: ${relative}`);
      const key = arguments_[1].fields;
      assert(registry.messages[key] === arguments_[2].fields.length, `changed argument contract in ${relative}: ${key}`);
      counts[key] = (counts[key] || 0) + 1;
      measuredCalls += 1;
    }
    assert(JSON.stringify(Object.entries(counts).sort()) === JSON.stringify(Object.entries(surface.calls).sort()), `unreported or missing localized calls in ${relative}`);
  }
}
assert(referenced.size === Object.keys(registry.messages).length && expectedCalls > 0, "incomplete message census");
if (check) assert(measuredCalls === expectedCalls, `partial call census: ${measuredCalls}/${expectedCalls}`);

const catalogPath = "crates/harn-stdlib/src/catalog_entries.rs";

use std::fs;
use std::path::Path;
use std::time::Duration;

use harn_provider_catalog::models_dev::{has_bindings, Snapshot, SOURCE_URL};
use sha2::{Digest, Sha256};

use crate::cli::ProvidersUpdateSourceArgs;

const CACHE_FILE: &str = "models-dev.json";

pub(super) fn resolve(source_dir: &Path, source: &str) -> Result<String, String> {
    let mut config: toml::Value = toml::from_str(source).map_err(|error| error.to_string())?;
    if !has_bindings(&config)? {
        return Ok(source.to_string());
    }
    let path = source_dir.join(CACHE_FILE);
    let body = fs::read_to_string(&path)
        .map_err(|error| format!("cannot read pinned Models.dev snapshot {}: {error}; generation never fetches live data", path.display()))?;
    let snapshot = Snapshot::parse(&body)?;
    snapshot.apply(&mut config)?;
    let normalized = toml::to_string_pretty(&config).map_err(|error| error.to_string())?;
    Ok(format!("# @generated by `harn provider catalog generate`; do not edit directly.\n# Sources: catalog_sources TOML and its pinned models-dev.json.\n{normalized}"))
}

pub(super) async fn update(args: &ProvidersUpdateSourceArgs) -> Result<(), String> {
    let bytes = if let Some(input) = &args.input {
        fs::read(input).map_err(|error| format!("cannot read {}: {error}", input.display()))?
    } else {
        let client = reqwest::Client::builder()
            .timeout(Duration::from_secs(30))
            .build()
            .map_err(|error| error.to_string())?;
        client
            .get(SOURCE_URL)
            .send()
            .await
            .map_err(|error| error.to_string())?
            .error_for_status()
            .map_err(|error| error.to_string())?
            .bytes()
            .await
            .map_err(|error| error.to_string())?
            .to_vec()
    };
    let upstream = serde_json::from_slice(&bytes)
        .map_err(|error| format!("invalid Models.dev JSON: {error}"))?;
    let (source, _) = super::build::provider_source_body(&args.source_dir)?;
    let config = toml::from_str(&source).map_err(|error| error.to_string())?;
    let digest = hex::encode(Sha256::digest(&bytes));
    let snapshot = Snapshot::capture(&upstream, &config, digest.clone())?;
    let body = serde_json::to_string_pretty(&snapshot).map_err(|error| error.to_string())? + "\n";
    let path = args.source_dir.join(CACHE_FILE);
    harn_vm::atomic_io::atomic_write(&path, body.as_bytes())
        .map_err(|error| format!("cannot replace {}: {error}", path.display()))?;
    println!("{}", crate::localization::formatted!("updated {} from Models.dev v2.0 SHA-256 {digest}; regenerate and review catalog projections before shipping", path.display(), digest = digest));
    Ok(())
}

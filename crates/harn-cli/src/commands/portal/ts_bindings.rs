const HEADER: &str = "\
// Generated by `make gen-portal-types` from the portal DTOs in
// crates/harn-cli/src/commands/portal. Do not edit by hand.

export type JsonValue = unknown
";

/// Collect `T::decl` for each listed type, so a type is exported exactly when
/// it is named here and a missing one fails `tsc` at its first reference.
macro_rules! declarations {
    ($cfg:expr; $($ty:ty),+ $(,)?) => {
        vec![$(<$ty as TS>::decl($cfg)),+]
    };
}

pub(super) fn render() -> String {
    // Wire integers are JSON numbers; `bigint` would not survive JSON.parse.
    let cfg = Config::new().with_large_int("number");
    let mut declarations: Vec<String> = declarations![&cfg;
        AutonomyTier, DaemonEventKindRecord, DaemonEventRecord, EnvironmentPolicyKind,
        ExecutionEvidenceRecord, FlightRecordingArtifact, FlightValuePolicy, GrantAudience,
        GrantReceipt, PersonaAssignmentStatus, PersonaBudgetStatus, PersonaHandoffInboxItem,
        PersonaLease, PersonaLifecycleState, PersonaQueuedWork, PersonaStatus,
        PersonaValueEventKind, PersonaValueReceipt, PortalActivity, PortalActivityAudit,
        PortalActivityAuditLayer, PortalArtifact, PortalCheckpoint, PortalChildRun,
        PortalCostReport, PortalCostSummary, PortalCostTrendPoint, PortalDlqAlert,
        PortalDlqAlertConfig, PortalDlqAttempt, PortalDlqBulkResponse, PortalDlqEntry,
        PortalDlqGroup, PortalDlqListResponse, PortalExecutionSummary, PortalHighlightKeywords,
        PortalInsight, PortalLaunchJob, PortalLaunchJobList, PortalLaunchTarget,
        PortalLaunchTargetList, PortalListResponse, PortalLlmOptions, PortalLlmProviderOption,
        PortalMeta, PortalPagination, PortalPolicySummary, PortalProviderCostBreakdown,
        PortalReplayAssertion, PortalReplaySummary, PortalRunDetail, PortalRunDiff,
        PortalRunSummary, PortalSkillMatchCandidate, PortalSkillMatchEvent,
        PortalSkillTimelineEntry, PortalSpan, PortalStage, PortalStageDebug, PortalStats,
        PortalStorySection, PortalTemplateBranch, PortalTemplateRender, PortalToolLoadEvent,
        PortalTranscriptMessage, PortalTranscriptStep, PortalTransition,
        PortalTrustGraphResponse, RunActionGraphEdgeRecord, RunActionGraphNodeRecord,
        RunDeliverableSummaryRecord, RunEvidenceGapRecord, RunExecutionRecord,
        RunObservabilityDiffRecord, RunObservabilityRecord, RunPlannerRoundRecord,
        RunStageDiffRecord, RunTaskLedgerSummaryRecord, RunTranscriptArtifactDescriptor,
        RunTranscriptPointerRecord, RunVerificationOutcomeRecord, RunWorkerLineageRecord,
        ToolCallDiffRecord, TrustAgentSummary, TrustChainReport, TrustOutcome, TrustRecord,
        TrustTraceGroup,
    ];
    declarations.sort();
    let mut out = String::from(HEADER);
    for declaration in declarations {
        out.push('\n');
        out.push_str("export ");
        out.push_str(&declaration);
        out.push('\n');
    }
    out
}

pub fn codegen_typescript() -> String {
    let config = Config::default();
    let mut output = String::from(
        "// GENERATED by `harn dump-protocol-artifacts` from harn-vm::codegen.\n\
         // Do not edit by hand. JSON integers use the lossless transport projection.\n\n\
         export type JsonValue = null | boolean | number | bigint | string | readonly JsonValue[] | { readonly [key: string]: JsonValue };\n\
         export type JsonSchema202012 = boolean | { readonly [keyword: string]: JsonValue };\n\n",
    );
    crate::tool_registry::append_tool_catalog_typescript(&mut output, &config);
    macro_rules! declaration {
        ($type:ty) => {{
            output.push_str("export ");
            output.push_str(&<$type as TS>::decl(&config));
            output.push_str("\n\n");
        }};
    }
    declaration!(WireTypeId);
    declaration!(WireLiteral);
    declaration!(WireIntegerEncoding);
    declaration!(WireBytesEncoding);
    declaration!(WireDecimalEncoding);
    declaration!(WireField);
    declaration!(WireDeclarationIdentity);
    declaration!(WireEnumVariant);
    declaration!(WireShape);
    declaration!(WireType);
    declaration!(WireFailureCode);
    declaration!(WireFailure);
    declaration!(CodegenSchemaVersion);
    declaration!(CodegenRequestVersion);
    declaration!(CodegenResponseVersion);
    declaration!(CodegenFeature);
    declaration!(CodegenRole);
    declaration!(CodegenIdentity);
    declaration!(CodegenPackage);
    declaration!(McpOutputEnvelope);
    declaration!(CodegenOutput);
    declaration!(CodegenBindingKind);
    declaration!(CodegenBinding);
    declaration!(CodegenCancellation);
    declaration!(CodegenExecution);
    declaration!(CodegenOperation);
    declaration!(CodegenIr);
    declaration!(CodegenRequest);
    declaration!(GeneratedRange);
    declaration!(GeneratedArtifact);
    declaration!(CodegenResponse);
    declaration!(CodegenDiagnosticCode);
    declaration!(CodegenDiagnostic);
    declaration!(NativeMcpBindingVersion);
    declaration!(NativeMcpOperationBinding);
    declaration!(NativeMcpBindingProfile);
    let facts = codegen_protocol_facts();
    let facts = facts.as_object().expect("protocol facts are an object");
    let mut names = facts.keys().collect::<Vec<_>>();
    names.sort();
    for name in names {
        output.push_str(&format!(
            "export const {name} = {} as const;\n",
            facts[name]
        ));
    }
    output
}

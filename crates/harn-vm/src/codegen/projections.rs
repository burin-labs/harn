fn contract_schema<T: JsonSchema>(artifact: &str, title: &str) -> Value {
    let generator = schemars::generate::SchemaSettings::draft2020_12()
        .for_deserialize()
        .into_generator();
    let mut schema = serde_json::to_value(generator.into_root_schema_for::<T>())
        .expect("codegen contract schema is serializable");
    schema["$id"] = json!(format!("https://harnlang.com/{artifact}"));
    schema["title"] = json!(title);
    schema
}


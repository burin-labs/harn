use serde_json::Value;

use super::*;

mod projections;

#[derive(Clone, Copy, PartialEq)]
enum Language {
    Swift,
    TypeScript,
}

pub fn typescript_declarations() -> String {
    declarations(Language::TypeScript).expect("provider catalog schema has a TypeScript projection")
}

pub fn swift_binding() -> Result<String, serde_json::Error> {
    declarations(Language::Swift).map_err(|error| {
        serde_json::Error::io(std::io::Error::new(std::io::ErrorKind::InvalidData, error))
    })
}

/// Generate from the embedded schema without loading user configuration.
pub fn swift_binding_embedded(
    _explicit_overlay: Option<&crate::config::ProvidersConfig>,
    _explicit_capabilities: Option<&crate::capabilities::CapabilitiesFile>,
) -> Result<String, serde_json::Error> {
    swift_binding()
}

fn declarations(language: Language) -> Result<String, String> {
    render_schema(&schema_value(), language)
}

fn render_schema(schema: &Value, language: Language) -> Result<String, String> {
    let label = match language {
        Language::Swift => "swift",
        Language::TypeScript => "typescript declarations",
    };
    let mut output = format!(
        "// GENERATED by `{PROVIDER_CATALOG_GENERATOR}` - do not edit by hand.\n\
         // Source: Harn runtime provider catalog schema v{PROVIDER_CATALOG_SCHEMA_VERSION}.\n\
         // Language: {label}.\n\n"
    );
    let definitions = schema["$defs"]
        .as_object()
        .ok_or("provider catalog schema is missing $defs")?;
    render_record(&mut output, &schema, "", language)?;
    for (key, definition) in definitions {
        let path = format!("/$defs/{key}");
        if definition.get("properties").is_some() && !projections::inline_record(&path, language) {
            render_record(&mut output, definition, &path, language)?;
        }
    }
    for path in projections::INLINE_RECORDS {
        render_record(
            &mut output,
            schema
                .pointer(path)
                .ok_or_else(|| format!("missing {path}"))?,
            path,
            language,
        )?;
    }
    for (name, path, equatable) in [
        ("HarnModelOperation", "/$defs/model_operation", true),
        (
            "HarnCatalogNoTrainingRequirement",
            "/$defs/data_controls/properties/no_training_requires/items",
            false,
        ),
    ] {
        let values = schema
            .pointer(path)
            .and_then(|value| value["enum"].as_array())
            .ok_or_else(|| format!("{path}: missing string enum"))?;
        match language {
            Language::Swift => {
                let equality = if equatable { ", Equatable" } else { "" };
                output.push_str(&format!(
                    "public enum {name}: String, Codable, Sendable{equality} {{\n"
                ));
                for value in values {
                    let case = value
                        .as_str()
                        .ok_or_else(|| format!("{path}: non-string enum"))?;
                    output.push_str(&format!("    case {case} = {value}\n"));
                }
                output.push_str("}\n\n");
            }
            Language::TypeScript if equatable => {
                let values = values
                    .iter()
                    .map(Value::to_string)
                    .collect::<Vec<_>>()
                    .join(" | ");
                output.push_str(&format!("export type {name} = {values}\n\n"));
            }
            Language::TypeScript => {}
        }
    }
    Ok(format!("{}\n", output.trim_end()))
}

fn required(schema: &Value, name: &str) -> bool {
    schema["required"]
        .as_array()
        .is_some_and(|fields| fields.iter().any(|field| field == name))
}

fn closed_properties<'a>(
    schema: &'a Value,
    path: &str,
) -> Result<&'a serde_json::Map<String, Value>, String> {
    if schema["additionalProperties"] != false {
        return Err(format!(
            "{path}: named object must declare additionalProperties false"
        ));
    }
    schema["properties"]
        .as_object()
        .ok_or_else(|| format!("{path}: missing properties"))
}

fn render_record(
    output: &mut String,
    schema: &Value,
    path: &str,
    language: Language,
) -> Result<(), String> {
    let name = projections::named_record(path, language)
        .ok_or_else(|| format!("{path}: missing public record name"))?;
    let properties = closed_properties(schema, path)?;
    match language {
        Language::TypeScript => {
            output.push_str(&format!("export interface {name} {{\n"));
            for (wire, property) in properties {
                let optional = if required(schema, wire) { "" } else { "?" };
                let ty = render_type(property, &format!("{path}/properties/{wire}"), language)?;
                output.push_str(&format!("  {wire}{optional}: {ty}\n"));
            }
            output.push_str("}\n\n");
        }
        Language::Swift => {
            output.push_str(&format!(
                "public struct {name}: Codable, Sendable, Equatable {{\n"
            ));
            let mut fields = Vec::new();
            for (wire, property) in properties {
                let field = projections::swift_field(path, wire);
                let mut ty = render_type(property, &format!("{path}/properties/{wire}"), language)?;
                let default = projections::swift_default(path, wire);
                if !required(schema, wire) && default.is_none() && !ty.ends_with('?') {
                    ty.push('?');
                }
                let access = if path == "/$defs/provider"
                    && matches!(
                        wire.as_str(),
                        "cache_usage_accounting" | "stream_usage_accounting"
                    ) {
                    "private"
                } else {
                    "public"
                };
                let (storage, initial) = if path == "/$defs/auth" && wire == "credential_env" {
                    ("var", " = nil")
                } else {
                    ("let", "")
                };
                output.push_str(&format!("    {access} {storage} {field}: {ty}{initial}\n"));
                fields.push((field, wire, ty, default));
            }
            if path == "/$defs/provider" {
                output.push_str("    public var cacheUsageAccounting: Bool { encodedCacheUsageAccounting ?? false }\n    public var streamUsageAccounting: Bool? { encodedStreamUsageAccounting }\n");
            }
            if fields
                .iter()
                .any(|(field, wire, _, default)| field != *wire || default.is_some())
            {
                output.push_str("\n    enum CodingKeys: String, CodingKey {\n");
                for (field, wire, _, _) in &fields {
                    let key = if field == *wire {
                        String::new()
                    } else {
                        format!(" = {wire:?}")
                    };
                    output.push_str(&format!("        case {field}{key}\n"));
                }
                output.push_str("    }\n");
            }
            if fields.iter().any(|(_, _, _, default)| default.is_some()) {
                output.push_str("\n    public init(from decoder: Decoder) throws {\n        let container = try decoder.container(keyedBy: CodingKeys.self)\n");
                // The model's display-name fallback reads the already decoded name.
                fields.sort_by_key(|(field, _, _, _)| field != "name");
                for (field, _, ty, default) in &fields {
                    let method = if ty.ends_with('?') || default.is_some() {
                        "decodeIfPresent"
                    } else {
                        "decode"
                    };
                    let ty = ty.trim_end_matches('?');
                    let fallback = default.map_or_else(String::new, |value| format!(" ?? {value}"));
                    output.push_str(&format!("        {field} = try container.{method}({ty}.self, forKey: .{field}){fallback}\n"));
                }
                output.push_str("    }\n");
            }
            output.push_str("}\n\n");
        }
    }
    Ok(())
}

fn render_type(schema: &Value, path: &str, language: Language) -> Result<String, String> {
    if let Some(reference) = schema["$ref"].as_str() {
        let path = reference
            .strip_prefix('#')
            .ok_or_else(|| format!("{path}: external reference {reference}"))?;
        if path == "/$defs/model_operation" {
            return Ok("HarnModelOperation".into());
        }
        if let Some(name) = projections::named_record(path, language) {
            return Ok(name.into());
        }
        let root = schema_value();
        return render_type(
            root.pointer(path)
                .ok_or_else(|| format!("missing reference {path}"))?,
            path,
            language,
        );
    }
    if language == Language::Swift
        && path == "/$defs/data_controls/properties/no_training_requires/items"
    {
        return Ok("HarnCatalogNoTrainingRequirement".into());
    }
    if let Some(values) = schema["enum"].as_array() {
        if !values.iter().all(Value::is_string) {
            return Err(format!("{path}: only string enums are supported"));
        }
        return Ok(match language {
            Language::Swift => "String".into(),
            Language::TypeScript => values
                .iter()
                .map(Value::to_string)
                .collect::<Vec<_>>()
                .join(" | "),
        });
    }
    if let Some(value) = schema.get("const") {
        return match value {
            Value::String(_) => Ok(match language {
                Language::Swift => "String".into(),
                Language::TypeScript if path == "/properties/schema" => "string".into(),
                Language::TypeScript => value.to_string(),
            }),
            Value::Number(value) if value.is_u64() || value.is_i64() => Ok(match language {
                Language::Swift => "Int".into(),
                Language::TypeScript => value.to_string(),
            }),
            _ => Err(format!("{path}: unsupported const {value}")),
        };
    }
    if let Some(kinds) = schema["type"].as_array() {
        if kinds.len() != 2 || !kinds.iter().any(|kind| kind == "null") {
            return Err(format!("{path}: unsupported type union {kinds:?}"));
        }
        let kind = kinds
            .iter()
            .find(|kind| *kind != "null")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{path}: invalid nullable type"))?;
        let ty = render_kind(kind, schema, path, language)?;
        return Ok(match language {
            Language::Swift => format!("{ty}?"),
            Language::TypeScript => format!("{ty} | null"),
        });
    }
    render_kind(
        schema["type"]
            .as_str()
            .ok_or_else(|| format!("{path}: missing supported schema type"))?,
        schema,
        path,
        language,
    )
}

fn render_kind(
    kind: &str,
    schema: &Value,
    path: &str,
    language: Language,
) -> Result<String, String> {
    let scalar = match (kind, language) {
        ("string", Language::Swift) => Some("String"),
        ("string", Language::TypeScript) => Some("string"),
        ("integer", Language::Swift) if path == "/$defs/pricing/properties/hosted_tool_fees/additionalProperties/properties/free_per_month" => Some("UInt64"),
        ("integer", Language::Swift) => Some("Int"),
        ("number", Language::Swift) => Some("Double"),
        ("integer" | "number", Language::TypeScript) => Some("number"),
        ("boolean", Language::Swift) => Some("Bool"),
        ("boolean", Language::TypeScript) => Some("boolean"),
        _ => None,
    };
    if let Some(scalar) = scalar {
        return Ok(scalar.into());
    }
    match kind {
        "array" => {
            let item = render_type(
                schema
                    .get("items")
                    .ok_or_else(|| format!("{path}: missing array items"))?,
                &format!("{path}/items"),
                language,
            )?;
            Ok(match language {
                Language::Swift => format!("[{item}]"),
                Language::TypeScript if item.contains(" | ") => format!("({item})[]"),
                Language::TypeScript => format!("{item}[]"),
            })
        }
        "object" if schema.get("properties").is_some() => {
            if let Some(name) = projections::named_record(path, language) {
                return Ok(name.into());
            }
            if language == Language::Swift {
                return Err(format!("{path}: Swift record needs a public name"));
            }
            let mut fields = Vec::new();
            for (name, property) in closed_properties(schema, path)? {
                let optional = if required(schema, name) { "" } else { "?" };
                fields.push(format!(
                    "{name}{optional}: {}",
                    render_type(property, &format!("{path}/properties/{name}"), language)?
                ));
            }
            Ok(format!("{{ {} }}", fields.join("; ")))
        }
        "object" => {
            let item = schema
                .get("additionalProperties")
                .filter(|value| value.is_object())
                .ok_or_else(|| format!("{path}: map needs a typed additionalProperties schema"))?;
            let item = render_type(item, &format!("{path}/additionalProperties"), language)?;
            Ok(match language {
                Language::Swift => format!("[String: {item}]"),
                Language::TypeScript => format!("Record<string, {item}>"),
            })
        }
        _ => Err(format!("{path}: unsupported schema type {kind}")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schema_changes_reach_both_projections_and_unrepresentable_shapes_refuse() {
        for language in [Language::Swift, Language::TypeScript] {
            let mut schema = schema_value();
            schema["properties"]["future_counter"] = serde_json::json!({"type": "integer"});
            let output = render_schema(&schema, language).expect("new field projects");
            let expected = match language {
                Language::Swift => "public let futureCounter: Int?",
                Language::TypeScript => "future_counter?: number",
            };
            assert!(output.contains(expected));
            schema["required"]
                .as_array_mut()
                .unwrap()
                .push("future_counter".into());
            let output = render_schema(&schema, language).expect("requiredness projects");
            assert!(!output.contains(expected));
            assert!(output.contains(match language {
                Language::Swift => "public let futureCounter: Int\n",
                Language::TypeScript => "future_counter: number\n",
            }));
            schema["properties"]["future_counter"]["type"] = "unrepresentable".into();
            assert!(render_schema(&schema, language)
                .unwrap_err()
                .contains("unsupported schema type unrepresentable"));
            schema = schema_value();
            schema["$defs"]["unregistered"] = serde_json::json!({
                "type": "object", "properties": {"value": {"type": "string"}},
                "additionalProperties": false
            });
            assert_eq!(
                render_schema(&schema, language).unwrap_err(),
                "/$defs/unregistered: missing public record name"
            );
        }
    }
}
